"""go2_sac / go2_ppo 共用的常量、环境和奖励配置、姿态小工具。

算法**无关**的那一层：两个训练入口（SAC / PPO）用的是同一个环境、同一套奖励，
所以这些只有一份。算法专属的超参在各自的 `TrainCfg` 里（`go2_sac/config.py` / `go2_ppo/config.py`）。

这里只依赖 numpy，**不 import mujoco**：reward / train / play 都要能在不建仿真环境的情况下
导入配置（play 要读 config.json、reward 要能单独做自检）。
"""

from __future__ import annotations

from dataclasses import asdict, dataclass
from pathlib import Path

import numpy as np

# ------------------------------------------------------------------ 路径

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SCENE = str(REPO_ROOT / "unitree_mujoco" / "unitree_robots" / "go2" / "scene.xml")
MODELS_DIR = REPO_ROOT / "models"
RUNS_DIR = REPO_ROOT / "runs"
CTRL_DIR = REPO_ROOT / "ctrl"

# ------------------------------------------------------------------ 常量

# 默认站姿，顺序与执行器/DDS 报文一致：FR, FL, RR, RL，每条腿 [hip, thigh, calf]。
# 取自 go2.xml 的 home 关键帧 qpos="0 0 0.27 1 0 0 0 0 0.9 -1.8 ..."。
DEFAULT_Q = np.array([0.0, 0.9, -1.8] * 4, dtype=np.float64)

# 时序。0.005 s 刻意等于 unitree_mujoco/simulate_python/config.py 里的 SIMULATE_DT，
# 让训练时的积分步长和 DDS 仿真完全一致，缩小 sim-to-sim 差距；
# 每个策略步走 4 个物理步 -> 策略 50 Hz（爬台阶需要比 50 Hz 更快的话再调 decimation）。
SIM_DT = 0.005
DECIMATION = 4

# 关节 PD 增益。这两个值在 DDS(200 Hz) 和直接步进(500 Hz) 两条路径上都实测稳定：
# 站立 z≈0.268 m、|dq|≈0，离 home 约 0.11 rad。
KP = 60.0
KD = 3.5

# 观测缩放/裁剪。观测维度 = 3(角速度) + 3(投影重力) + 2(航向 sin,cos) + 3(指令) + 12(关节角)
#                        + 12(关节速) + 12(上一步动作)
#
# 航向那 2 维是 2026-10-10 加的，位置**必须在投影重力之后、指令之前**（下标 6:8）：
# `go2_issac/smoke.py` 按 `obs[0, 3:6]` 切投影重力，插在 6:8 不动任何绝对下标。
# 为什么是 sin/cos 而不是裸 yaw：绕 ±π 不连续，MLP 学不平；sin/cos 天然在 ±1 内，OBS_CLIP 不裁剪。
# 为什么必须有：`projected_gravity` 取不出 yaw（重力向量绕竖直轴旋转不变），所以改之前策略对
# "自己朝哪"是**完全失明**的——只看得到 gyro(=ω_z 速率) 和倾斜。而奖励里 `yaw`(−1.0·(1−cos yaw))
# 和 `lateral`(−0.3·y²) 罚的都是绝对量，策略看不见就学不会纠偏，只能白交税
# （实测 rl_800000 逐步 −0.093 与 −0.510，两项占每步支出的 73%）。
OBS_GYRO_SCALE = 0.25
OBS_CMD_SCALE = 2.0
OBS_DQ_SCALE = 0.05
OBS_CLIP = 10.0
OBS_DIM = 47

# ------------------------------------------------------------ 前方地形高度扫描
#
# **为什么需要它（2026-10-13 加的，理由是被实测逼出来的）**：
# 上面那 47 维**没有任何前方地形信息**，狗只能靠**撞上去**发现台阶。
# 于是它学到的必然是"针对某个高度调好的固定抬腿反射"，而不是"看见多高就迈多高"。
# 实测出来的后果是一道**陡崖**（不是斜坡）：
#   `s076/best` 在 25 局口径下，第一级立面 0.133 m → 95%，0.136 m → 55%，0.143 m → 25%。
# 而**腿本身完全没有问题**：`footclear.py` 量出狗能把脚抬到离地 0.37~0.58 m，
# 目标立面才 0.15 m。**所以卡点是信息，不是能力。**
#
# 扫描是"前方一条线"（机体系、沿机头方向），不是 3D 高度图：
# 楼梯在 y 方向是均匀的，一行足够，而且 16 维比 3×16 维更容易在暖启动时被学会。
# 存的是**相对支撑面的高度差**（见 env._scan），平地上一律是 0，与绝对高度无关。
SCAN_N = 16
SCAN_X = (-0.32, 1.28)   # 相对机身的前后范围（m）：-0.32 到机身后脚，+1.28 给约 1 m 前瞻
SCAN_SCALE = 2.0         # 和 OBS_CMD_SCALE 同量级；配合 OBS_CLIP=10 可表示 ±5 m
OBS_SCAN_DIM = SCAN_N


def obs_dim(privileged: bool = False, scan: bool = False) -> int:
    """观测维度。privileged=True 时多 1 维"机身高出当地地形的高度"；
    scan=True 时再多 16 维前方地形高度扫描（见 SCAN_N 处的注释）。"""
    return OBS_DIM + (1 if privileged else 0) + (OBS_SCAN_DIM if scan else 0)


# ------------------------------------------------------------------ 姿态小工具


def quat_to_rpy(quat) -> np.ndarray:
    """四元数 (w, x, y, z) -> 欧拉角 (roll, pitch, yaw)，ZYX 顺序，单位 rad。"""
    w, x, y, z = (float(v) for v in quat)
    roll = np.arctan2(2.0 * (w * x + y * z), 1.0 - 2.0 * (x * x + y * y))
    pitch = np.arcsin(np.clip(2.0 * (w * y - z * x), -1.0, 1.0))
    yaw = np.arctan2(2.0 * (w * z + x * y), 1.0 - 2.0 * (y * y + z * z))
    return np.array([roll, pitch, yaw], dtype=np.float64)


def projected_gravity(quat) -> np.ndarray:
    """世界系重力方向在机体系下的分量（单位向量）。

    注意用的是四元数而不是加速度计：DDS 的 LowState 里有四元数，仿真和真机都能算，
    加速度计在动起来以后噪声大得多。
    """
    w, x, y, z = (float(v) for v in quat)
    return np.array(
        [2.0 * (w * y - x * z), -2.0 * (y * z + w * x), 2.0 * (x * x + y * y) - 1.0],
        dtype=np.float64,
    )


# ------------------------------------------------------------------ 配置


@dataclass
class EnvCfg:
    """环境配置。默认值就是"直接能训"的一套，注释里写了实测依据。"""

    scene: str = DEFAULT_SCENE
    terrain: str = "full"  # flat / steps / full，见 terrain.build_model
    # 地形高度的整体缩放，用来做课程：0.3 时两个槛只有 2.4 cm、六级台阶每级只升 4.5 cm，
    # 1.0 就是原场景。只缩放几何体的高度（size[2]/pos[2]），x/y 脚印不动，所以台阶的踏面深度
    # 不变、只是变矮——这正是想要的"变简单"。0 就是纯平地。
    # **为什么必须做课程**：实测平地训出来的策略在槛高 0.04~0.06 时能爬上去，到 0.08 就突然
    # 0/3 全卡住（断层很硬）。直接从平地跳到 0.08，策略只会停在槛前拿 track_lin_vel 的保底分。
    terrain_scale: float = 1.0

    # --- 多尺度混合（domain randomization），None = 旧行为、逐位不变
    # (lo, hi) 时**训练侧**给每个 worker 分一个固定的 scale（见 train_utils.make_env），
    # 于是同一份 replay buffer 里会同时有平地和不同高度的台阶。
    # **动机**：单档训练的实测规律是"在哪档练就只在哪档变好"（修复记录 §6.8：R16 在 0.80
    # 练出 +2 局，代价是 0.84 −3 局）。policy 看不到地形、也就分不清当前是哪一档，
    # 跨档混合是让它学不到"某一档专用步态"的最省事办法。
    # **评估侧永远钉死 None**（train_utils.EvalMetricsCallback._mk）：选模 key 必须是
    # 一把固定尺子量出来的，混进训练分布就没法跨 run 比大小了。
    terrain_scale_range: tuple = None

    # --- 时序与增益
    sim_dt: float = SIM_DT
    decimation: int = DECIMATION
    kp: float = KP
    kd: float = KD
    # 关节目标 = 默认站姿 + action_scale * 动作。**这个值决定了狗能跨多高的槛，不是随便调的**。
    #
    # 测法是直接跑：拿手调开环小跑（无反馈）撞槛，扫出「绝对摆幅 -> 能跨过的最高槛」：
    #
    #     action_scale   0.04m  0.06m  0.08m  0.10m  0.12m
    #         0.40        过     卡     卡     卡     卡
    #         0.50        过     过     卡     卡     卡
    #         0.60        过     过     卡     卡     卡
    #         0.80        过     过     过     过     卡
    #
    # 带反馈的策略比这套开环小跑大约好一档（0.40 时开环只能过 0.04，平地训出来的策略能过 0.06）。
    # 场景里那两个槛是 0.08 m，所以要 0.6 才有戏；0.4 时策略会走到 x≈0.94（机身前缘正好顶在
    # x=1.1 的槛面上）就停住，20 万步毫无进展——这不是奖励或探索的问题，是幅度不够。
    action_scale: float = 0.6
    joint_margin: float = 0.05  # 目标角离关节硬限位保留的余量，免得一直顶在限位上

    # --- 回合
    max_episode_s: float = 20.0
    cmd_vx: tuple = (0.4, 0.8)  # 每回合随机的前进速度指令，m/s

    # --- 重置分布
    reset_x: tuple = (-0.3, 0.3)
    reset_y: float = 0.15  # y 在 ±0.15 内随机
    # --- 近台阶出生（只在 reset_frac_stair > 0 时启用；默认 0 = 老行为，逐位不变）
    # **动机**：reset_x 默认 (-0.3, 0.75)（full 阶段实际用的），到第一个立面 x=2.10 还有
    # 1.35~2.40 m，而一个回合只有 1000 步。实测全程 3268 步里 3220 步（98.5%）都花在平地
    # 上，真正接触台阶的只有 48 步 —— 爬台阶的梯度被平地步态稀释掉了。
    # 窗口 1.40~1.85 是**按脚印算出来的**：出生高度取 terrain.top_footprint(half_x=0.24)
    # （env.py），1.85+0.24=2.09 < 2.10，整只狗都还在第一个立面之前，不会一出生就站在台阶上
    # （那会直接跳过"上第一级"这个最难的技能）；同时还剩 0.25~0.70 m 助跑。
    reset_x_stair: tuple = (1.40, 1.85)
    # 用这个窗口出生的回合比例。0 = 关闭（评估环境**永远**按 0 建，见 train_utils）。
    # 画过界也不能算错：>0 时才多抽一个 uniform()，等于换了一条 RNG 流，
    # 所以固定种子的历史评估结果只在 0 时保持逐位可比。
    reset_frac_stair: float = 0.0
    reset_yaw: float = 0.20  # 偏航在 ±0.20 rad 内随机
    reset_z: tuple = (0.30, 0.33)  # home 关键帧的脚底会陷进地面约 18 mm，抬高一点让它自己落稳

    # --- 观测
    # True 时额外给 1 维"机身高出当地地形的高度"。这一维对爬台阶很有用，但 DDS 的
    # LowState 里没有（只有 rt/sportmodestate 才有位置），所以默认关掉，保证策略能直接上真机。
    privileged: bool = False
    # True 时额外给 16 维前方地形高度扫描（见 SCAN_N 处的长注释）。
    # 真机上深度相机 + elevation mapping 可以提供它，但**本仓库没实现**；
    # 所以默认关，开了就说明这个策略依赖仿真里的真值扫描，不能直接上真机。
    scan: bool = False

    # --- 终止 / 成功判据
    fall_clearance: float = 0.10  # 机身低于当地地形这么多就判摔倒（阈值依据见 AGENT.md §5-C3）
    flip_rad: float = 1.0  # |roll| 或 |pitch| 超过它判翻转（阈值依据见 AGENT.md §5-C3）
    out_y: float = 2.5
    out_x_back: float = -1.0
    # 顶台阶顶面 0.92 m，x∈[3.14, 3.66]，平台深 0.52 m。不取 x>=3.6：那里离 0.92 m 悬崖
    # 只剩 6 cm，会奖励"冲过终点再摔下去"。
    goal_x: float = 3.30
    # goal_z 是 env 建好地形后按 terrain.top(goal_x) + goal_clearance 算出来的，**不是**这里的值
    # （为什么不能写死见 AGENT.md §5-C4）。
    goal_z: float = 1.05
    goal_clearance: float = 0.15  # 站上顶面时 base 约比顶面高 0.27，留 0.15 表示确实站在高处
    goal_y: float = 1.0


@dataclass
class RewardCfg:
    """奖励权重。**项名 = reward.py 里的函数名，权重就是这里的同名字段**，一一对应。

    调权重时优先动这里，别去改 reward.py 的函数体。
    """

    # --- 前进 / 高度
    # progress 是这套奖励里唯一的大额收入来源，要压得住其它所有项，而站着不动必须**恒等于 0**。
    # 它现在是**势能** γ·x'−x（见 reward._progress），不再是"每步付一次"的速度年金：
    # 单位从"分/步"变成"分/米"，100.0 对应走起来约 +1~2 分/步、走完全程约 190 分。
    progress: float = 100.0
    track_lin_vel: float = 1.0  # 速度跟踪（步态质量，金额很小）
    # 带折扣的地形势能 γ·h(x')−h(x)。**必须给足量**：0.08 m 的槛 × 2.0 只有 0.16 分，
    # 而卡在槛上时 height+collision 一步就 -0.13，爬上去净亏 → 策略学会不爬（实测确凿）。
    #
    # 20.0 是量出来的错值：整段楼梯只涨 0.57 m，20.0 只兑现 11 分，而同期 progress 年金
    # 付了 250 分——爬楼的收益比不爬只高 23%，梯度一直在教策略"别爬"。progress 改成势能后
    # 前进的总收入是 (x_cap−x_0)·100 ≈ 190 分，高度按"值前进的一半"配：0.57·W ≈ 95 → W≈170，
    # 取 100（宁可让高度略轻于水平，也不要它盖过主导项把步态压垮）。
    # 2026-10-13 由 200 → 340（**第二次提价**，同样是量出来的，理由见下）。
    # 2026-10-12 由 100 → 200：**楼梯整体定价过低**是"回报涨、台阶数掉"的直接原因之一。
    # 实测（20 局确定性评估，models/go2_sac_full/best）：整段 0.92 m 楼梯只兑现
    # climb 92 + level_bonus 30 + success 20 = 142 分，而平地小跑的**年金**收入是 98.0 分/秒
    # —— 142 分等于 1.45 s 的平地步态。等价地说：一次"上第一级"的尝试
    # （成功兑现 +22、失败被打回 −20）要 **47.6%** 的保持率才回本，而实测满高时的保持率
    # 只有 5%（20 局里 1 局）。→ 200 之后回本线降到 8.5%，实测的 5% 尝试变成正期望。
    # 注意这一项是**势能**（telescoping，原地站着恒为 0），所以提高它不会产生平摊税/白拿年金。
    climb: float = 340.0
    # 2026-10-13 新增：**按步计价的"驻级收入"** = level_income × 当前站上的级数。
    # 和 `level_bonus` 配成一对：**登上一级**给一次性奖励（level_bonus），
    # **待在那一级**每步都给钱（这一项）。
    #
    # **为什么必须加**：`climb` 是望远镜位势，一局的爬升总收入 = `h_末 − h_始`。
    # 在**爬得上去**的高度上这没问题；但在能力边界之上（实测 1.00 档，20 局），
    # 狗"爬上去 → 掉下来"的净高度变化**恰好是 0**，于是 `climb` 项实测**整项为 0**，
    # `success_bonus` 也是 0，而"去试"要付 `collision −128/局 + orientation −45/局`。
    # → **"不试"是严格最优**，确定性策略每局稳定亏 5.8 分。这不是畏缩，是算对了。
    # 而 47 维观测里没有地形信息，策略没法把"别试"限制在难的档位上，
    # 于是一次微调就把邻档一起带下去 —— 这就是 R9~R19 每次坍缩、以及
    # "当档特化"（§6.8）的统一机制。完整推导见修复记录 §7.3~§7.8。
    #
    # **为什么按级数而不是按米**：先写的版本是 `× terrain_h`，实测发现它会把钱发给
    # **x=1.10~1.70 那两个 0.08 m 的槛**（1.00 档上 20 局白拿 +172/局，狗本来就在槛上蹲着）。
    # 于是"从槛爬上第 1 级"的真实差价只剩 `0.170−0.08 = 0.09 m`，被摊薄掉了。
    # 按级数计就没有这个问题：`terrain.level_at_height` 的定义里槛就是 **0 级**
    # （0.08 < 第一级 0.170），所以槛上收入严格为 0，**不需要任何魔法常数**。
    #
    # 它**故意不是望远镜位势**（那正是要修的东西），所以确实会产生"驻级年金"。
    # 与 AGENT.md §5-B1 否决的"**速度**年金"的区别：速度年金能在原地抖动刷分，
    # 驻级年金刷不了 —— 级数由 `support_height`（四脚下方地形高度的**中位数**）算出，
    # 要至少三只脚真的站上去才涨。
    #
    # 量级（用 §7.3 的实测帐目校准）：0.4 时，1.00 档上"爬上第 1 级并待到回合结束"
    # （约 700 步）收入 0.4×1×700 = +280，加登台阶一次的 climb +58，
    # 对 −173 的尝试成本净 **+165**，正期望。第 2 级翻倍，梯度一直指向更高处。
    level_income: float = 0.4
    # 2026-10-12 由 5 → 20：和 climb 同一次改动，都是"把楼梯的价钱提到它该有的位置"。
    # 每登上**一级新台阶**的一次性奖励，离散信号比连续势能好认。上限是 6 级 ×20 = 120 分/局，
    # 而且是按 episode 内 max 比较（env.py 的 prev_max_level），下去再上来不能重新领（B8）。
    # 可被利用面：每级最多领一次、且必须四脚支撑高度的中位数真的到了新一级（至少要两只脚
    # 站上去），所以"冲上去领奖再退回来"最多只能骗 6 次 ×20 —— 真爬一趟是它的 6 倍以上。
    level_bonus: float = 20.0
    base_height: float = -0.3  # **惩罚**：离当地地形的高度偏差（项函数返回 |err|），站对了是 0
    # 2026-10-10 置 0（保留字段与函数体，老 config.json 与 POSTURE_TERMS 都按名字引用它）。
    # 降权理由：罚的是**绝对横向位置 y²**，而观测里没有 y（也没有任何绝对位姿），
    # 策略看不见就学不会纠偏。实测它是**最大的一笔支出**：rl_800000 平地 6 局 −0.510/步，
    # 而同期最大收入才 +0.669/步。位置性的约束改由 progress 的走廊权重 w(y) 承担
    # （|y|≥1.25 处前进奖励归零，见 §5-B5），那条路是挂在"走"上的，不会变成平摊税。
    lateral: float = 0.0
    # 世界系横向速度的平方（= 旧 lateral 罚项 y² 的时间导数，直接对应"漂出走廊"）。
    # **必须取世界系**：实测手调开环小跑 10 局，世界系 vy²=0.0462、|vy|=0.186，
    # 而机体系 vy² 只有 0.0022——差 21 倍。也就是说这台狗的横漂**几乎全是"机头偏了、
    # 沿机身直走"**造成的，不是真的侧滑。罚机体系等于罚了个寂寞。
    # 对比：[lateral] 那个 y² 是不可观测的白交税，而这一项在加了航向观测之后**基本可推断**
    # （yaw 已知 ⇒ vy_world ≈ −sin(yaw)·vx），所以它从"税"变成了"可控制项"。
    # 权重标定 @ −5.0：手调小跑（起始步态）vy²=0.0462 → −0.23/步；干净直行 ~0.0025 → ~−0.01/步。
    # 每步最大收入 = track 0.97 + progress 0.35 ≈ +1.32，−0.23 占 ~17%：压得住漂移、
    # 又留了 ~20 倍的好/坏区分度。**若发现策略退化成原地趴窝**（低指令端有过这个退化均衡：
    # 站着不动零收入也零支出、vy=0 零代价），说明压过头了，降到 −3.0。
    lateral_vel: float = -5.0

    # --- 姿态
    orientation: float = -0.5
    yaw: float = -1.0  # 地形关于 y 对称、外面是无限平地，不压住航向就会横着漂
    yaw_rate: float = -0.25

    # --- 平滑 / 能耗
    action_rate: float = -0.05
    torques: float = -1e-4
    collision: float = -0.002  # 按接触力缩放：擦碰不等于猛撞

    # --- 终止
    # 2026-10-12 由 20 → 60。成功判据（到 x≥3.30 且 z≥顶面+0.15 的高台）**一个字没改**，
    # 改的只是它值多少分（§3 规则 7 说的是不许放松判据，不是不许定价）。
    # 和 climb/level_bonus 一起，整段楼梯的专属收入从 142 分提到 364 分，而到台阶前的
    # "无风险"平路收入约 286 分（progress 190 + track 95）—— 之前楼梯比平路还便宜。
    #
    # 2026-10-13 由 60 → 450（**第二次提价**）。2026-10-12 那次提价**没有解决退化**，
    # 所以这次不再凭"楼梯应该值多少钱"的直觉，而是直接量"老实爬"和"放弃"两条路的差价。
    #
    # 量法：`python -m go2_sac.diag reward <模型> <scale>`（逐项逐步累加成整回合账）。
    # 实测的**每回合净分**（去权重前的原始量 × 当时的权重）：
    #
    #   | 策略 | scale | 步数/回合 | 旧定价 (climb 200) | 新定价 (climb 340) |
    #   |---|---|---|---|---|
    #   | `s076/best` 老实爬 | 0.76 | 418 | **+364.8** | +646.6 |
    #   | `s080` 退化后的"冲几步就翻滚" | 0.76 | 162 | +213.8 | +251.0 |
    #   | `s076/best` 老实爬 | **0.80** | 537 | **+171.7** | +306.1 |
    #   | `s080` 同一条 | **0.80** | 153 | **+142.6** | +165.4 |
    #
    # **关键不是"退化策略分高"（它其实更低），是差价在塌缩**：
    # 0.76 上老实爬是退化的 1.71 倍（那里**学得动**），到 0.80 只剩 **1.20 倍**（那里七次全崩）。
    #
    # **但 SAC 优化的是打折回报，不是"每回合净分"，这才是真正的判据。**
    # 老实爬要 537 步才挣完，放弃只要 153 步——按 `gamma=0.995` 折现
    # （G = r·(1−γ^N)/(1−γ)），把上面的数换算过去：
    #
    #   | 策略 | r/步 | N | **G（折现）** | 差价 | 实测结局 |
    #   |---|---|---|---|---|---|
    #   | 老实爬 @0.76 旧定价 | 0.873 | 418 | **+153.1** | **+4.3%** | **学得动**（R4/R8/R9） |
    #   | 放弃 @0.76 旧定价 | 1.320 | 162 | +146.8 | | |
    #   | 老实爬 @0.80 旧定价 | 0.320 | 537 | +59.6 | **−67%** | **七次全崩** |
    #   | 放弃 @0.80 旧定价 | 0.932 | 153 | **+99.8** | | |
    #
    # **这条判据被"唯一已知会学"的那一档验证过**（0.76 旧定价 +4.3% → 学得动），
    # 所以拿它反解 0.80 要多少 `success` 才能翻正：**≈382**。
    # 取 **450** 留出余量（0.80 翻到 +7%，0.76 更是 +88%）。
    #
    # **机理**：惩罚项**按时间**收，楼梯收入**按"爬了多高"封顶**。老实爬要多活 384 步，
    # 多付一遍税，而多爬的高度**一分钱不多给**——所以"少活一会儿"本身就是收益。
    # 这正是用户报的"回报涨、台阶数掉"：在旧定价下，那两件事是同一件事。
    #
    # 为什么 `success` 的杠杆效率最高：**退化策略完全刷不到它**（它从不上顶台，
    # 实测登顶 0/6），而 `climb` 两条路都按比例拿（2.4 : 1），提 climb 会被退化侧分掉。
    # **`level_bonus` 刻意不动**：它是唯一"冲上去领奖再退回来"能刷的项
    # （每级一次、退下来不回收），提它等于给捷径加钱。
    #
    # ⚠️ 还没用上的下一个杠杆（若本轮仍塌，直接从这儿接着做）：**把 `gamma` 提到 0.998**。
    # 0.995 的有效视野是 200 步，而老实爬的回合是 537 步——**它的后半段收入被打折打没了**。
    # 同样用上表算：gamma=0.998 时 0.80 变成 老实爬 +187.7 对 放弃 +142.3（+32%）。
    # 但那是个全局改动（Q 值尺度、方差都会变），所以**先只动权重、一次只改一层**。
    success: float = 450.0
    # 摔倒的代价。progress 改成势能后，"多活一会儿"不再自动等于"多拿分"——但在楼梯中途摔下去
    # 仍然是净亏：climb 项会把已经兑现的 0.57 m 高度收回去，而重爬要再顶一遍碰撞和力矩惩罚。
    # -5.0 那次是配着"progress 年金"估的，那时摔跤的主要代价是丢掉剩余年金（几百步×1分），
    # 年金没了，这个数就得自己把它补上，否则策略会拿"摔了算逑"去赌快跑。
    #
    # 2026-10-12 **试过调大，最后没有调**：full 阶段退化出来的那个"冲 1.8 m 就地翻滚"
    # 为什么划算？实测它 20 局全是摔倒，但每局先拿走 +247.8 的助跑收入（progress 161 +
    # track 83），只付 25 分罚款，净 +172.3 —— 而老实磨台阶的那个策略是 −35.9。看着像
    # "摔得太便宜"，但两个数一算就知道加大罚款救不了：把翻滚从 +172 压到 −36 需要
    # fall ≈ −233，而**失败尝试的摔倒率实测是 45~95%**（满高时 9~19/20 局摔），
    # 罚款一加上去先被压死的就是我们最需要的"敢去试"。正确的杠杆是**把楼梯的价钱提上去**
    # （见上面 climb / level_bonus / success），不是把摔倒的价钱压下来。
    fall: float = -25.0

    # --- 各项的内部参数
    # 高斯速度跟踪的分母（形式上是 σ²）。0.25 时站着不动还能拿 exp(-0.6²/0.25)=0.20，
    # 是"站着不动"第二大的一笔白拿收入；收到 0.1 后只剩 0.027。
    track_sigma: float = 0.1
    height_target: float = 0.27  # 站立时 base 离地高度
    height_dead_zone: float = 0.05  # 高度偏差的死区（为什么需要见 AGENT.md §5-B4）
    collision_force_free: float = 25.0  # 接触力的免罚底噪，牛顿（见 AGENT.md §5-B4）
    climb_gamma: float = 1.0  # climb 项的折扣，**必须为 1.0**（推导见 AGENT.md §5-B2）
    progress_y_gate: float = 1.25  # 前进奖励的走廊宽度闸门（防刷分，见 AGENT.md §5-B5）
    progress_x_cap: float = 3.5  # 过了这里不再给前进奖励


def to_jsonable(obj) -> dict:
    """把配置数据类转成可以写进 config.json 的普通 dict（tuple 转 list）。"""
    return asdict(obj)
